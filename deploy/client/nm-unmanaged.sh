#!/bin/bash
# Make NetworkManager stop managing prrr's TUN devices.
#
# NM adopts foreign TUN devices and auto-activates a profile for them. A later
# profile deactivation flushes the tunnel address while the prrr client still
# owns the device fd; injected packets are then sourced from a LAN address, the
# server's masquerade rule (scoped to the tunnel subnet) stops matching them,
# and the tunnel silently degrades into a one-way black hole while the routing
# hook keeps reporting "UP".
# See specs/bugs/BUG-network-manager-tun-address-loss.md.
#
# The exclusion is scoped to `prrr*`: every other interface (an OpenVPN `tun0`,
# LAN, Wi-Fi, …) keeps its normal NetworkManager treatment.
#
# Usage:
#   nm-unmanaged.sh                      write to /etc/NetworkManager/conf.d
#   PRRR_NM_CONF_DIR=<dir> nm-unmanaged.sh   write elsewhere (used by tests)
#
# Apply immediately afterwards (needs root, not done here so the write stays
# testable without touching a live NetworkManager):
#   nmcli general reload CONFIG   ||   kill -HUP $(pidof NetworkManager)
set -euo pipefail

CONF_DIR="${PRRR_NM_CONF_DIR:-/etc/NetworkManager/conf.d}"
CONF_FILE="${CONF_DIR}/99-prrr-unmanaged.conf"

mkdir -p "$CONF_DIR"
cat > "$CONF_FILE" <<'CONF'
# Generated by prrr — deploy/client/nm-unmanaged.sh. Do not edit by hand.
# prrr's route hook owns its TUN devices; NM must not flush their addresses.
[keyfile]
unmanaged-devices+=interface-name:prrr*
CONF

echo "$CONF_FILE"
