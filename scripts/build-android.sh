#!/usr/bin/env bash
# FRD: specs/frds/FRD-M001-mobile-workspace.md
#
# Build prrr-mobile for Android targets and create AAR
#
# Usage:
#   export NDK_HOME=/path/to/ndk
#   ./scripts/build-android.sh              # Build release
#   DEBUG=1 ./scripts/build-android.sh      # Build debug

set -euo pipefail

# Configuration
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
MOBILE_DIR="${PROJECT_ROOT}/prrr-mobile"
OUTPUT_DIR="${PROJECT_ROOT}/target"

PROFILE="${DEBUG:+debug}"
PROFILE="${PROFILE:-release}"
PROFILE_FLAG=""
if [ "${PROFILE}" = "release" ]; then
    PROFILE_FLAG="--release"
fi

# Android targets and their JNI architecture names
declare -A ANDROID_TARGETS=(
    ["aarch64-linux-android"]="arm64-v8a"
    ["armv7-linux-androideabi"]="armeabi-v7a"
    ["x86_64-linux-android"]="x86_64"
    ["i686-linux-android"]="x86"
)

LIB_NAME="libprrr_mobile.so"
AAR_NAME="prrr_mobile.aar"

echo "==> Building prrr-mobile for Android (${PROFILE} profile)"

# Check NDK_HOME
if [ -z "${NDK_HOME:-}" ]; then
    echo "Error: NDK_HOME environment variable not set" >&2
    echo "" >&2
    echo "Set NDK_HOME to your Android NDK installation:" >&2
    echo "  export NDK_HOME=/path/to/android-ndk" >&2
    echo "" >&2
    echo "Download NDK from:" >&2
    echo "  https://developer.android.com/ndk/downloads" >&2
    exit 1
fi

if [ ! -d "${NDK_HOME}" ]; then
    echo "Error: NDK_HOME directory does not exist: ${NDK_HOME}" >&2
    exit 1
fi

# Verify Android targets are installed
echo "==> Checking Android targets..."
for target in "${!ANDROID_TARGETS[@]}"; do
    if ! rustup target list --installed | grep -q "^${target}$"; then
        echo "Error: Target ${target} not installed" >&2
        echo "Install with: rustup target add ${target}" >&2
        exit 1
    fi
done

# Configure cargo for Android NDK (create config if not present)
CARGO_CONFIG="${PROJECT_ROOT}/.cargo/config.toml"
CARGO_CONFIG_BACKUP=""
NEEDS_CONFIG=false

if [ ! -f "${CARGO_CONFIG}" ]; then
    mkdir -p "${PROJECT_ROOT}/.cargo"
    CARGO_CONFIG_BACKUP="new"
    NEEDS_CONFIG=true
elif ! grep -q "aarch64-linux-android" "${CARGO_CONFIG}" 2>/dev/null; then
    CARGO_CONFIG_BACKUP="${CARGO_CONFIG}.backup.$$"
    cp "${CARGO_CONFIG}" "${CARGO_CONFIG_BACKUP}"
    NEEDS_CONFIG=true
fi

# Detect NDK version and toolchain path
NDK_VERSION=$(ls "${NDK_HOME}/toolchains/llvm/prebuilt" | head -1)
TOOLCHAIN="${NDK_HOME}/toolchains/llvm/prebuilt/${NDK_VERSION}/bin"

if [ ! -d "${TOOLCHAIN}" ]; then
    echo "Error: Android toolchain not found at ${TOOLCHAIN}" >&2
    exit 1
fi

# Add Android linker configuration only if needed
if [ "$NEEDS_CONFIG" = true ]; then
    cat >> "${CARGO_CONFIG}" << EOF

# Android NDK linkers (auto-generated by build-android.sh)
[target.aarch64-linux-android]
linker = "${TOOLCHAIN}/aarch64-linux-android21-clang"

[target.armv7-linux-androideabi]
linker = "${TOOLCHAIN}/armv7a-linux-androideabi21-clang"

[target.x86_64-linux-android]
linker = "${TOOLCHAIN}/x86_64-linux-android21-clang"

[target.i686-linux-android]
linker = "${TOOLCHAIN}/i686-linux-android21-clang"
EOF
else
    echo "==> Android linker configuration already present, skipping..."
fi

# Build for each target
echo "==> Building for Android targets..."
cd "${PROJECT_ROOT}"
for target in "${!ANDROID_TARGETS[@]}"; do
    echo "  -> Building for ${target}..."
    cargo build -p prrr-mobile --target "${target}" ${PROFILE_FLAG}
done

# Create AAR structure
echo "==> Creating AAR..."
AAR_BUILD_DIR="${OUTPUT_DIR}/aar-build"
rm -rf "${AAR_BUILD_DIR}"
mkdir -p "${AAR_BUILD_DIR}"

# Copy native libraries
for target in "${!ANDROID_TARGETS[@]}"; do
    jni_arch="${ANDROID_TARGETS[$target]}"
    jni_dir="${AAR_BUILD_DIR}/jni/${jni_arch}"
    mkdir -p "${jni_dir}"
    cp "${OUTPUT_DIR}/${target}/${PROFILE}/${LIB_NAME}" "${jni_dir}/"
done

# Create AndroidManifest.xml
cat > "${AAR_BUILD_DIR}/AndroidManifest.xml" << 'EOF'
<?xml version="1.0" encoding="utf-8"?>
<manifest xmlns:android="http://schemas.android.com/apk/res/android"
    package="com.prrr.mobile">
    <uses-sdk android:minSdkVersion="26" />
</manifest>
EOF

# Create classes.jar (empty for native-only library)
mkdir -p "${AAR_BUILD_DIR}/classes"
(cd "${AAR_BUILD_DIR}/classes" && jar cf ../classes.jar .)

# Create R.txt (empty)
touch "${AAR_BUILD_DIR}/R.txt"

# Package as AAR (AAR is just a ZIP with specific structure)
AAR_PATH="${OUTPUT_DIR}/${AAR_NAME}"
echo "  -> Packaging AAR..."
(cd "${AAR_BUILD_DIR}" && zip -q -r "${AAR_PATH}" .)

# Cleanup
rm -rf "${AAR_BUILD_DIR}"

# Restore original cargo config if we modified it
if [ -n "${CARGO_CONFIG_BACKUP}" ]; then
    if [ "${CARGO_CONFIG_BACKUP}" = "new" ]; then
        # Remove the file we created
        rm -f "${CARGO_CONFIG}"
        rmdir "${PROJECT_ROOT}/.cargo" 2>/dev/null || true
    else
        # Restore backup
        mv "${CARGO_CONFIG_BACKUP}" "${CARGO_CONFIG}"
    fi
fi

echo "==> Build complete!"
echo "    AAR: ${AAR_PATH}"
echo ""
echo "To use in Android Studio:"
echo "  1. Copy ${AAR_NAME} to your project's libs/ directory"
echo "  2. Add to build.gradle:"
echo "     implementation files('libs/${AAR_NAME}')"
