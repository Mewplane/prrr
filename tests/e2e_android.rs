/// Full end-to-end: server in Podman + Android emulator + deep link config import.
///
/// 1. Start prrr server in container
/// 2. Boot Android emulator
/// 3. Install APK
/// 4. Generate compressed config URL with server's actual IP
/// 5. Inject via deep link intent (bypasses camera)
/// 6. Verify the app processes the config (check logcat for success markers)
#[test]
#[ignore]
fn e2e_android_deep_link_config_import() {
    // --- Server setup ---
    let mut orch = PodmanOrchestrator::new("android");
    orch.build_image().expect("build image");
    orch.create_network().expect("create network");
    orch.create_volume().expect("create volume");

    let server_ip = orch.start_server("masque").expect("start server");
    orch.wait_for_server_ready(SERVER_READY_TIMEOUT)
        .unwrap_or_else(|e| {
            let logs = orch.logs(Container::Server).unwrap_or_default();
            panic!("server not ready: {e}\n--- server logs ---\n{logs}");
        });

    // Read the client config the server generated
    let config_output = orch.exec(Container::Server, &["cat", "/shared/client.toml"])
        .expect("read client config");
    let config_toml = String::from_utf8_lossy(&config_output.stdout).to_string();
    assert!(!config_toml.is_empty(), "client config must not be empty");

    // Compress to import URL
    let import_url = compress_to_import_url(&config_toml);

    // --- Emulator setup ---
    let mut emu = AndroidEmulator::new(AVD_NAME);

    if !AndroidEmulator::emulator_available() {
        eprintln!("SKIP: Android emulator not available");
        return;
    }
    if !AndroidEmulator::adb_available() {
        eprintln!("SKIP: adb not available");
        return;
    }

    // Check APK exists
    if !std::path::Path::new(APK_PATH).exists() {
        eprintln!("SKIP: APK not found at {APK_PATH}. Run `make android-debug` first.");
        return;
    }

    emu.start().expect("start emulator");
    emu.wait_for_boot(EMULATOR_BOOT_TIMEOUT)
        .expect("emulator boot");

    emu.install_apk(APK_PATH).expect("install APK");

    // --- Deep link injection ---

    // Clear logcat buffer so we only see logs from this test
    let _ = emu.shell("logcat -c");

    emu.inject_config_via_deeplink(&import_url)
        .expect("inject config via deep link");

    // Wait for the app to process the deep link
    std::thread::sleep(Duration::from_secs(5));

    // Check logcat for evidence the deep link config was actually processed.
    // We look for the specific client name from the server-generated config
    // to confirm the full pipeline worked (deep link → decompress → parse → save).
    // Dump all app logs — broader filter to catch errors
    let logcat = emu.shell("logcat -d | grep -E 'prrr|MainActivity|ConfigurationManager|Deep link|uniffi|MobileException' | tail -100")
        .expect("read logcat");

    // The config generated by the server contains "e2e-client" as client name.
    // If the deep link was processed, the app logs about saving configuration
    // or at minimum the Rust parser ran on the actual config data.
    eprintln!("--- logcat ---\n{logcat}");

    assert!(
        logcat.contains("Configuration saved") || logcat.contains("e2e-client"),
        "deep link config must be processed — expected 'Configuration saved' or 'e2e-client' in logcat."
    );
}

/// Full end-to-end: server in Podman + Android emulator + deep link import + VPN tunnel.
///
/// 1. Start prrr server in container
/// 2. Boot Android emulator
/// 3. Install APK, grant VPN permission
/// 4. Inject config via deep link
/// 5. Trigger VPN connect
/// 6. Verify tunnel is up (tun0 exists) and traffic flows (ping server-side VPN IP)
#[test]
#[ignore]
fn e2e_android_vpn_tunnel() {
    const PACKAGE: &str = "com.prrr.vpn.android";

    // --- Server setup (publish port so emulator can reach it via 10.0.2.2) ---
    let mut orch = PodmanOrchestrator::new("android-vpn");
    orch.build_image().expect("build image");
    orch.create_network().expect("create network");
    orch.create_volume().expect("create volume");

    const HOST_PORT: u16 = 10443;
    let _server_ip = orch.start_server_with_opts("masque", Some(HOST_PORT)).expect("start server");
    orch.wait_for_server_ready(SERVER_READY_TIMEOUT)
        .unwrap_or_else(|e| {
            let logs = orch.logs(Container::Server).unwrap_or_default();
            panic!("server not ready: {e}\n--- server logs ---\n{logs}");
        });

    // Read the server-generated client config
    let config_output = orch.exec(Container::Server, &["cat", "/shared/client.toml"])
        .expect("read client config");
    let config_toml = String::from_utf8_lossy(&config_output.stdout).to_string();
    assert!(!config_toml.is_empty(), "client config must not be empty");

    // Rewrite endpoint to emulator's host gateway (10.0.2.2 is the host from emulator)
    let config_toml = config_toml
        .lines()
        .map(|line| {
            if line.trim_start().starts_with("endpoint") {
                format!("endpoint = \"10.0.2.2:{HOST_PORT}\"")
            } else {
                line.to_string()
            }
        })
        .collect::<Vec<_>>()
        .join("\n");

    let import_url = compress_to_import_url(&config_toml);

    // --- Emulator setup ---
    let mut emu = AndroidEmulator::new(AVD_NAME);

    if !AndroidEmulator::emulator_available() || !AndroidEmulator::adb_available() {
        eprintln!("SKIP: emulator or adb not available");
        return;
    }
    if !std::path::Path::new(APK_PATH).exists() {
        eprintln!("SKIP: APK not found at {APK_PATH}");
        return;
    }

    emu.start().expect("start emulator");
    emu.wait_for_boot(EMULATOR_BOOT_TIMEOUT).expect("emulator boot");
    emu.install_apk(APK_PATH).expect("install APK");

    // Grant VPN permission (bypasses the consent dialog)
    emu.grant_vpn_permission(PACKAGE).expect("grant VPN permission");

    // --- Inject config ---
    let _ = emu.shell("logcat -c");
    emu.inject_config_via_deeplink(&import_url).expect("inject config");
    std::thread::sleep(Duration::from_secs(5));

    // Verify config was saved
    let logcat = emu.shell("logcat -d | grep -E 'MainActivity|ConfigurationManager' | tail -20")
        .expect("read logcat");
    assert!(
        logcat.contains("Configuration saved") || logcat.contains("Deep link config saved"),
        "config must be saved before connecting.\n--- logcat ---\n{logcat}"
    );

    // --- Trigger VPN connect via deep link (runs inside app process, has VPN permission) ---
    let _ = emu.shell("logcat -c");
    emu.inject_config_via_deeplink("prrr://connect").expect("trigger connect");

    // Wait for tunnel to establish
    let mut tunnel_up = false;
    for _ in 0..VPN_ESTABLISH_TIMEOUT.as_secs() {
        std::thread::sleep(Duration::from_secs(1));
        if emu.check_vpn_active().unwrap_or(false) {
            tunnel_up = true;
            break;
        }
    }

    let logcat = emu.shell("logcat -d | grep -E 'PrrrVpnService|VpnManager|prrr' | tail -30")
        .expect("read logcat");
    eprintln!("--- vpn logcat ---\n{logcat}");

    assert!(tunnel_up, "VPN tunnel (tun0) must be active.\n--- logcat ---\n{logcat}");

    // Verify the Rust tunnel reached Connected state
    assert!(
        logcat.contains("Rust tunnel pipeline started") || logcat.contains("CONNECTED"),
        "tunnel pipeline must start.\n--- logcat ---\n{logcat}"
    );

    // --- Verify traffic ---
    // Ping the server's VPN-side IP (10.66.66.1 is the first IP in the 10.66.66.0/24 subnet)
    let ping_ok = emu.ping("10.66.66.1").unwrap_or(false);

    if !ping_ok {
        // Dump routing info for debugging
        let routes = emu.shell("ip route show").unwrap_or_default();
        let ifconfig = emu.shell("ip addr show tun0").unwrap_or_default();
        eprintln!("--- routes ---\n{routes}");
        eprintln!("--- tun0 ---\n{ifconfig}");
    }

    assert!(ping_ok, "must be able to ping server through VPN tunnel");
}

