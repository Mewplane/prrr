//! Android emulator e2e tests.
//!
//! Tests the full flow: server in Podman → build and install APK on emulator →
//! inject config via deep link → verify VPN tunnel establishes.
//!
//! Requires: Podman, Android emulator (AVD), Android SDK (adb), /dev/net/tun.
//!
//! ```bash
//! cargo test --test e2e_android -- --ignored --nocapture
//! ```

mod support;

use std::time::Duration;

use base64::Engine;
use base64::engine::general_purpose::{STANDARD, URL_SAFE_NO_PAD};
use flate2::Compression;
use flate2::write::DeflateEncoder;
use std::io::Write;

use support::emulator::AndroidEmulator;
use support::podman::{PodmanOrchestrator, Container};

const SERVER_READY_TIMEOUT: Duration = Duration::from_secs(30);
const EMULATOR_BOOT_TIMEOUT: Duration = Duration::from_secs(300);
const VPN_ESTABLISH_TIMEOUT: Duration = Duration::from_secs(30);

const APK_PATH: &str = "prrr-android/app/build/outputs/apk/debug/app-debug.apk";
const AVD_NAME: &str = "prrr_test";

/// Compress a TOML config to a prrr://import?z=... URL.
fn compress_to_import_url(config_toml: &str) -> String {
    let mut encoder = DeflateEncoder::new(Vec::new(), Compression::best());
    encoder.write_all(config_toml.as_bytes()).unwrap();
    let compressed = encoder.finish().unwrap();
    let encoded = URL_SAFE_NO_PAD.encode(&compressed);
    format!("prrr://import?z={encoded}")
}

